'use strict';
/**
 * Builds userscript/queup-dead-song-finder.user.js: one file a person can install in Tampermonkey or Violentmonkey.
 *
 * It puts the pieces together (the song matching and the reading of QueUp's answers, shared with the bot, then the
 * core and the panel) in one scope, nothing else is added and nothing is downloaded. The pieces are written
 * as Node modules, and each one gets its own `module` and a `require` that finds the others.
 *
 *   node tools/build-userscript.js          writes the file
 *   node tools/build-userscript.js --check  says if the file in the repo is out of date (the tests do this)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const PIECES = [
  ['songMatch', 'lib/songMatch.js'],
  ['queupParse', 'lib/queupParse.js'],
  ['core', 'userscript/src/core.js'],
  ['ui', 'userscript/src/ui.js']
];
const OUTPUT = path.join(root, 'userscript', 'queup-dead-song-finder.user.js');

function build() {
  const header = fs.readFileSync(path.join(root, 'userscript/src/header.txt'), 'utf8').trim();

  const modules = PIECES.map(function(piece) {
    const code = fs.readFileSync(path.join(root, piece[1]), 'utf8').trim();
    return [
      '// ---- ' + piece[1] + ' ----',
      '__modules[' + JSON.stringify(piece[0]) + '] = (function () {',
      'var module = { exports: {} };',
      'var exports = module.exports;',
      'var require = __require;',
      code,
      'return module.exports;',
      '})();'
    ].join('\n');
  }).join('\n\n');

  return [
    header,
    '',
    '(function () {',
    "'use strict';",
    '',
    '// the pieces, built from the files named below (see tools/build-userscript.js), do not edit this file',
    'var __modules = {};',
    "function __require(name) { return __modules[String(name).replace(/^.*\\//, '').replace(/\\.js$/, '')]; }",
    '',
    modules,
    '',
    '// start, once, in the top window of the page only',
    "if (window.top === window.self && !document.getElementById('queup-dead-song-finder')) {",
    "  __modules.ui.start(__modules.core);",
    '}',
    '})();',
    ''
  ].join('\n');
}

if (require.main === module) {
  const built = build();

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== built) {
      console.error('userscript/queup-dead-song-finder.user.js is out of date, run: node tools/build-userscript.js');
      process.exit(1);
    }
    console.log('userscript is up to date');
  } else {
    fs.writeFileSync(OUTPUT, built);
    console.log('wrote ' + path.relative(root, OUTPUT) + ' (' + built.length + ' characters)');
  }
}

module.exports = { build: build, OUTPUT: OUTPUT };
