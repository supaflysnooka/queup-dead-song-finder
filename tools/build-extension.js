'use strict';
/**
 * Builds the browser extension, from the same pieces as the userscript, into extension/build/chrome and
 * extension/build/firefox (each one can be loaded as it is, see extension/README.md), and with --zip into
 * extension/dist/ as the files the browser stores take.
 *
 *   node tools/build-extension.js          writes extension/build
 *   node tools/build-extension.js --zip    also writes extension/dist/*.zip
 *   node tools/build-extension.js --check  says if extension/build is out of date (the tests do this)
 *
 * The content script is the userscript's code with extension/src/shim.js in place of the userscript manager; the
 * background script is extension/src/background.js. Nothing else is added and nothing is downloaded.
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const root = path.resolve(__dirname, '..');
const BUILD = path.join(root, 'extension', 'build');
const DIST = path.join(root, 'extension', 'dist');
const ICONS = [16, 48, 128];

const PIECE_CODE = function(name, file) {
  const code = fs.readFileSync(path.join(root, file), 'utf8').trim();
  return [
    '// ---- ' + file + ' ----',
    '__modules[' + JSON.stringify(name) + '] = (function () {',
    'var module = { exports: {} };',
    'var exports = module.exports;',
    'var require = __require;',
    code,
    'return module.exports;',
    '})();'
  ].join('\n');
};

const WRAP_START = [
  '(function () {',
  "'use strict';",
  '',
  '// the pieces, built from the files named below (see tools/build-extension.js), do not edit this file',
  'var __modules = {};',
  "function __require(name) { return __modules[String(name).replace(/^.*\\//, '').replace(/\\.js$/, '')]; }",
  '// Firefox has `browser` (with promises), Chrome has `chrome`',
  "var __api = typeof browser !== 'undefined' && browser.runtime ? browser : chrome;",
  ''
].join('\n');

function version() {
  return /^\/\/ @version\s+(\S+)/m.exec(fs.readFileSync(path.join(root, 'userscript/src/header.txt'), 'utf8'))[1];
}

function contentScript() {
  const pieces = [['songMatch', 'lib/songMatch.js'], ['queupParse', 'lib/queupParse.js'], ['core', 'userscript/src/core.js'], ['ui', 'userscript/src/ui.js'], ['shim', 'extension/src/shim.js']];
  return [
    WRAP_START,
    pieces.map(function(piece) { return PIECE_CODE(piece[0], piece[1]); }).join('\n\n'),
    '',
    '// what the userscript manager gives a userscript, here from the extension (see extension/src/shim.js)',
    'var GM_getValue, GM_setValue, GM_xmlhttpRequest;',
    '',
    '// start, once, in the top window of the page only',
    "if (window.top === window.self && !document.getElementById('queup-dead-song-finder')) {",
    '  __modules.shim.load(__api).then(function(gm) {',
    '    GM_getValue = gm.GM_getValue;',
    '    GM_setValue = gm.GM_setValue;',
    '    GM_xmlhttpRequest = gm.GM_xmlhttpRequest;',
    '    __modules.ui.start(__modules.core);',
    '  });',
    '}',
    '})();',
    ''
  ].join('\n');
}

function backgroundScript() {
  return [
    WRAP_START,
    PIECE_CODE('background', 'extension/src/background.js'),
    '',
    '__modules.background.listen(__api, fetch);',
    '})();',
    ''
  ].join('\n');
}

function manifest(target) {
  const m = {
    manifest_version: 3,
    name: 'QueUp Dead Song Finder',
    version: version(),
    description: "Finds songs in your own QueUp playlists that can't be played anymore, and finds clear replacements. Nothing changes until you click Apply.",
    homepage_url: 'https://github.com/supaflysnooka/queup-dead-song-finder',
    icons: { '16': 'icons/icon-16.png', '48': 'icons/icon-48.png', '128': 'icons/icon-128.png' },
    permissions: ['storage'],
    host_permissions: ['https://www.youtube.com/*'],
    content_scripts: [{ matches: ['https://queup.net/*'], js: ['content.js'], run_at: 'document_idle', all_frames: false }]
  };

  if (target === 'chrome') {
    m.background = { service_worker: 'background.js' };
  } else {
    // Firefox doesn't run service workers for extensions, it takes a background script
    m.background = { scripts: ['background.js'] };
    m.browser_specific_settings = { gecko: { id: 'dead-song-finder@queup-dead-song-finder.github.io', strict_min_version: '140.0', data_collection_permissions: { required: ['none'] } } };
  }
  return JSON.stringify(m, null, 2) + '\n';
}

/** @returns {Object<string, Buffer|string>} every file of both builds, by its path under extension/build */
function build() {
  const files = {};
  ['chrome', 'firefox'].forEach(function(target) {
    files[target + '/manifest.json'] = manifest(target);
    files[target + '/content.js'] = contentScript();
    files[target + '/background.js'] = backgroundScript();
    ICONS.forEach(function(size) { files[target + '/icons/icon-' + size + '.png'] = fs.readFileSync(path.join(root, 'extension/icons/icon-' + size + '.png')); });
  });
  return files;
}

// ---- zip (the stores take a zip), written here so nothing has to be installed ----

function crc32(buffer) {
  var crc = 0xffffffff;
  for (var i = 0; i < buffer.length; i++) {
    crc ^= buffer[i];
    for (var k = 0; k < 8; k++) { crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1)); }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/** @param {{name: string, data: Buffer}[]} entries */
function zip(entries) {
  const parts = [];
  const central = [];
  let offset = 0;

  entries.forEach(function(entry) {
    const name = Buffer.from(entry.name, 'utf8');
    const packed = zlib.deflateRawSync(entry.data);
    const crc = crc32(entry.data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);         // version needed
    local.writeUInt16LE(0x0800, 6);     // names are UTF-8
    local.writeUInt16LE(8, 8);          // deflate
    local.writeUInt16LE(0, 10);         // time
    local.writeUInt16LE(0x21, 12);      // date: 1980-01-01, so the same input gives the same file
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(packed.length, 18);
    local.writeUInt32LE(entry.data.length, 22);
    local.writeUInt16LE(name.length, 26);
    parts.push(local, name, packed);

    const dir = Buffer.alloc(46);
    dir.writeUInt32LE(0x02014b50, 0);
    dir.writeUInt16LE(20, 4);
    dir.writeUInt16LE(20, 6);
    dir.writeUInt16LE(0x0800, 8);
    dir.writeUInt16LE(8, 10);
    dir.writeUInt16LE(0, 12);
    dir.writeUInt16LE(0x21, 14);
    dir.writeUInt32LE(crc, 16);
    dir.writeUInt32LE(packed.length, 20);
    dir.writeUInt32LE(entry.data.length, 24);
    dir.writeUInt16LE(name.length, 28);
    dir.writeUInt32LE(offset, 42);
    central.push(dir, name);

    offset += local.length + name.length + packed.length;
  });

  const centralSize = central.reduce(function(total, part) { return total + part.length; }, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat(parts.concat(central, [end]));
}

function writeBuild(files) {
  fs.rmSync(BUILD, { recursive: true, force: true });
  Object.keys(files).forEach(function(name) {
    const to = path.join(BUILD, name);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, files[name]);
  });
}

function writeZips(files) {
  fs.mkdirSync(DIST, { recursive: true });
  ['chrome', 'firefox'].forEach(function(target) {
    const entries = Object.keys(files).filter(function(name) { return name.indexOf(target + '/') === 0; })
      .map(function(name) { return { name: name.slice(target.length + 1), data: Buffer.from(files[name]) }; });
    const file = path.join(DIST, 'queup-dead-song-finder-' + target + '-' + version() + '.zip');
    fs.writeFileSync(file, zip(entries));
    console.log('wrote ' + path.relative(root, file));
  });
}

/** what is out of date: the files whose content differs from the build, or that should not be there */
function outOfDate(files) {
  const wrong = [];
  Object.keys(files).forEach(function(name) {
    const file = path.join(BUILD, name);
    if (!fs.existsSync(file) || !Buffer.from(files[name]).equals(fs.readFileSync(file))) { wrong.push(name); }
  });
  const onDisk = [];
  (function walk(folder, prefix) {
    if (!fs.existsSync(folder)) { return; }
    fs.readdirSync(folder, { withFileTypes: true }).forEach(function(entry) {
      if (entry.isDirectory()) { walk(path.join(folder, entry.name), prefix + entry.name + '/'); } else { onDisk.push(prefix + entry.name); }
    });
  })(BUILD, '');
  onDisk.forEach(function(name) { if (!(name in files)) { wrong.push(name); } });
  return wrong;
}

if (require.main === module) {
  const files = build();

  if (process.argv.includes('--check')) {
    const wrong = outOfDate(files);
    if (wrong.length) { console.error('extension/build is out of date (' + wrong.join(', ') + '), run: node tools/build-extension.js'); process.exit(1); }
    console.log('extension is up to date');
  } else {
    writeBuild(files);
    console.log('wrote extension/build (version ' + version() + ')');
    if (process.argv.includes('--zip')) { writeZips(files); }
  }
}

module.exports = { build: build, outOfDate: outOfDate, zip: zip, version: version, BUILD: BUILD };
